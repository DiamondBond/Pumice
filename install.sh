#!/bin/sh
# install.sh [light|dark] [colour|grey]
# Links the Pumice themes into ~/.themes, loads the panel and rofi styling, sets the xfwm4
# and panel options the theme is drawn for, binds Ctrl+Shift+F5 to the light/dark
# switch and applies one variant. Everything it changes is saved once to revert.sh.
set -e
cd "$(dirname "$0")"
x() { xfconf-query -c xfce4-panel -p "$@"; }
q() { xfconf-query -c "$1" -p "$2" 2>/dev/null; }
# id of the first panel plugin of a given type (ids differ between setups)
id_of() { xfconf-query -c xfce4-panel -lv | awk -v t="$1" '$1 ~ /^\/plugins\/plugin-[0-9]+$/ && $2 == t { sub(/.*-/, "", $1); print $1; exit }'; }

menu=$(id_of applicationsmenu) tasks=$(id_of tasklist) pager=$(id_of pager)
gtkcss=${XDG_CONFIG_HOME:-$HOME/.config}/gtk-3.0/gtk.css
import='@import url("'"$HOME"'/.local/share/pumice/current/panel.css");'
key='/commands/custom/<Primary><Shift>F5'
rofi=${XDG_CONFIG_HOME:-$HOME/.config}/rofi/config.rasi
kg=${XDG_CONFIG_HOME:-$HOME/.config}/kdeglobals
qt='export QT_QPA_PLATFORMTHEME=kde  # pumice'   # tagged, so revert.sh leaves a line of your own alone
# KDE apps are only touched where Breeze's colour schemes are installed, as in pumice-mode.sh
kde=
[ -f /usr/share/color-schemes/BreezeLight.colors ] && kde=1
# pumice-mode.sh's colour-group swap: file 1 without its colour groups, then file 2's
swap='FNR == 1 { s = 0 } /^\[/ { s = /^\[(Colors|ColorEffects):/ } FILENAME == ARGV[1] ? !s : s'

[ -f revert.sh ] || {
  echo '#!/bin/sh'
  echo '# Generated by install.sh: puts back what it changed, then removes itself.'
  for t in Pumice Pumice-dark Pumice-grey Pumice-dark-grey; do echo "rm -f ~/.themes/$t"; done
  echo "rm -rf ~/.local/share/pumice"
  [ -e "$rofi" ] && echo "sed -i '\\|pumice/current/rofi.rasi|d' '$rofi'" || echo "rm -f '$rofi'"
  echo "sed -i '\\|pumice/current/panel.css|d' '$gtkcss'"
  echo "xfconf-query -c xsettings -p /Net/ThemeName -s '$(q xsettings /Net/ThemeName)'"
  echo "xfconf-query -c xfwm4 -p /general/theme -s '$(q xfwm4 /general/theme)'"
  echo "xfconf-query -c xfce4-notifyd -p /theme -n -t string -s '$(q xfce4-notifyd /theme || echo Default)'"
  echo "xfconf-query -c xfwm4 -p /general/button_layout -s '$(q xfwm4 /general/button_layout)'"
  echo "xfconf-query -c xfwm4 -p /general/title_font -s '$(q xfwm4 /general/title_font)'"
  echo "xfconf-query -c xfce4-panel -p /panels/dark-mode -n -t bool -s $(q xfce4-panel /panels/dark-mode || echo false)"
  echo "xfconf-query -c xfce4-panel -p /panels/panel-1/background-style -n -t uint -s $(q xfce4-panel /panels/panel-1/background-style || echo 0)"
  echo "xfconf-query -c xfce4-panel -p /panels/panel-1/icon-size -n -t uint -s $(q xfce4-panel /panels/panel-1/icon-size || echo 0)"
  [ -n "$menu" ] && {
    echo "xfconf-query -c xfce4-panel -p /plugins/plugin-$menu/show-button-title -n -t bool -s $(q xfce4-panel /plugins/plugin-$menu/show-button-title || echo true)"
    echo "xfconf-query -c xfce4-panel -p /plugins/plugin-$menu/button-icon -n -t string -s '$(q xfce4-panel /plugins/plugin-$menu/button-icon || echo org.xfce.panel.applicationsmenu)'"
  }
  [ -n "$tasks" ] && echo "xfconf-query -c xfce4-panel -p /plugins/plugin-$tasks/show-handle -n -t bool -s $(q xfce4-panel /plugins/plugin-$tasks/show-handle || echo true)"
  [ -n "$pager" ] && echo "xfconf-query -c xfce4-panel -p /plugins/plugin-$pager/miniature-view -n -t bool -s $(q xfce4-panel /plugins/plugin-$pager/miniature-view || echo true)"
  q xfce4-keyboard-shortcuts "$key" >/dev/null || echo "xfconf-query -c xfce4-keyboard-shortcuts -p '$key' -r"
  echo "gsettings set org.gnome.desktop.interface color-scheme $(gsettings get org.gnome.desktop.interface color-scheme)"
  # kdeglobals: put back the colour groups it had and keep the rest, which KDE
  # apps may have written to since; drop the file if that leaves nothing
  [ -n "$kde" ] && {
    mkdir -p "$(dirname "$kg")"
    cp "$kg" "$kg.pumice-bak" 2>/dev/null || touch "$kg.pumice-bak"
    printf '%s\n' "awk '$swap' '$kg' '$kg.pumice-bak' > '$kg.tmp' && mv '$kg.tmp' '$kg'; rm -f '$kg.pumice-bak'; [ -s '$kg' ] || rm -f '$kg'"
  }
  echo "[ -f ~/.xprofile ] && sed -i '/^$qt\$/d' ~/.xprofile"
  echo "xfce4-panel -r"
  # spent once run, so the next install records the settings afresh
  echo 'rm -f "$0"'
} > revert.sh && chmod +x revert.sh

# themes
mkdir -p ~/.themes
for t in Pumice Pumice-dark Pumice-grey Pumice-dark-grey; do ln -sfn "$PWD/$t" ~/.themes/$t; done

# panel styling: one import, pointed at the current variant by pumice-mode.sh
mkdir -p "$(dirname "$gtkcss")"; touch "$gtkcss"
grep -qF "$import" "$gtkcss" || printf '\n%s\n' "$import" >> "$gtkcss"

# rofi: themed to follow the current variant (a later @theme in config.rasi wins)
mkdir -p "$(dirname "$rofi")"; touch "$rofi"
grep -qF pumice/current/rofi.rasi "$rofi" || printf '\n@theme "%s"\n' "$HOME/.local/share/pumice/current/rofi.rasi" >> "$rofi"

# Qt: the KDE platform theme, so KDE apps take their icons and colours from kdeglobals
# (which pumice-mode.sh keeps in step) instead of GTK's icon theme; read at login.
# Left alone if another platform theme (qt6ct, ...) is in use or already set there
[ -n "$kde" ] && [ "${QT_QPA_PLATFORMTHEME:-kde}" = kde ] &&
  ! grep -q '^export QT_QPA_PLATFORMTHEME=' ~/.xprofile 2>/dev/null && printf '\n%s\n' "$qt" >> ~/.xprofile

# xfwm4: buttons on the right with no app-icon menu (Alt+Space or right-click
# on the title still opens it); the corner pieces are drawn for this layout
xfconf-query -c xfwm4 -p /general/button_layout -s '|HMC'
xfconf-query -c xfwm4 -p /general/title_font -s 'Sans Semi-Bold 10'

# panel: let the theme paint it; 16px icons so the menu ball renders sharp
x /panels/panel-1/background-style -n -t uint -s 0
x /panels/panel-1/icon-size -n -t uint -s 16
[ -n "$menu" ] && {
  x /plugins/plugin-$menu/show-button-title -n -t bool -s false
  x /plugins/plugin-$menu/button-icon -n -t string -s "$HOME/.local/share/pumice/current/menu.svg"
}
[ -n "$tasks" ] && x /plugins/plugin-$tasks/show-handle -n -t bool -s false
[ -n "$pager" ] && x /plugins/plugin-$pager/miniature-view -n -t bool -s false   # buttons mode: drawn as dots

# Ctrl+Shift+F5 toggles light/dark, unless that key is already taken
q xfce4-keyboard-shortcuts "$key" >/dev/null ||
  xfconf-query -c xfce4-keyboard-shortcuts -p "$key" -n -t string -s "$PWD/pumice-mode.sh"

./pumice-mode.sh "${1:-light}" "${2:-colour}"
